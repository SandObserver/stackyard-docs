/* Gates the build output. Run after `npm run build`. */
import { readFileSync, existsSync, statSync } from 'node:fs';
import { globSync } from 'node:fs';
import { relative, join } from 'node:path';

const DIST = 'dist';
const SRC_ROOTS = ['src', 'scripts', 'public/api', 'public/icons', 'public/img'];
const ROOT_FILES = ['README.md', 'astro.config.mjs', 'package.json', '.gitignore'];
const ASSET_EXT = /\.(svg|png|jpe?g|webp|ico|css|js|json|txt|xml|webmanifest|woff2)$/i;
const BANNED = /claude|anthropic|generated by|ai-generated|chatgpt|openai|copilot/i;

const read = (f) => readFileSync(f, 'utf8');
const html = globSync(`${DIST}/**/*.html`);
if (html.length === 0) {
  console.error('No HTML in dist. Run `npm run build` first.');
  process.exit(1);
}

const problems = [];
const report = (group, list) => {
  console.log(`[${group.padEnd(7)}] ${list.length}`);
  list.slice(0, 8).forEach((x) => console.log(`    ${x}`));
  problems.push(...list.map((x) => `${group}: ${x}`));
};

/* Pages and their anchors. */
const pages = new Set(['/']);
const anchors = new Map();
for (const f of html.filter((f) => f.endsWith('index.html'))) {
  const p = ('/' + relative(DIST, f).replace(/index\.html$/, '')).replace(/\/+$/, '') + '/';
  pages.add(p);
  anchors.set(p, new Set([...read(f).matchAll(/id="([^"]+)"/g)].map((m) => m[1])));
}

/* Internal links and fragments. */
const linkBad = new Set();
for (const f of html) {
  for (const [, href, frag] of read(f).matchAll(/href="(\/[^"#?]*)(#[^"]*)?"/g)) {
    if (href.startsWith('//') || ASSET_EXT.test(href)) continue;
    const norm = href.endsWith('/') ? href : href + '/';
    if (!pages.has(norm)) linkBad.add(`no page  ${href}${frag ?? ''}`);
    else if (frag && !anchors.get(norm).has(frag.slice(1))) linkBad.add(`no anchor ${href}${frag}`);
  }
}
report('links', [...linkBad].sort());

/* Every local asset a page references must exist. */
const assetBad = new Set();
for (const f of html) {
  for (const [, a] of read(f).matchAll(/(?:src|href|content)="(\/[^"?#]*\.[a-z0-9]+)"/gi)) {
    if (!ASSET_EXT.test(a)) continue;
    if (!existsSync(join(DIST, a))) assetBad.add(a);
  }
}
report('assets', [...assetBad].sort());

/* Nothing authored here may name the tooling used to build it. */
/* This file carries the pattern it searches for, so it excludes itself. */
const SELF = 'scripts/check-dist.mjs';
const files = [
  ...SRC_ROOTS.flatMap((r) => globSync(`${r}/**/*`)),
  ...ROOT_FILES.filter(existsSync),
]
  .filter((f) => f !== SELF && statSync(f).isFile() && statSync(f).size < 3_000_000)
  /* Binary bytes produce meaningless matches. */
  .filter((f) => !/\.(png|jpe?g|webp|ico|woff2?)$/i.test(f));
report('hygiene', files.filter((f) => BANNED.test(read(f))));

/* Nothing authored here may carry a credential or a real private address.
   Scoped to what this repository writes. public/js and public/widgets are
   verbatim copies of the application and carry its own placeholders. */
const SECRET = [
  [/(gh[pousr]_|github_pat_)[A-Za-z0-9_]{20,}/, 'GitHub token'],
  [/\bsk-[A-Za-z0-9]{20,}/, 'API key'],
  [/\bAKIA[0-9A-Z]{16}\b/, 'AWS key id'],
  [/\bAIza[0-9A-Za-z_-]{20,}/, 'Google API key'],
  [/\bxox[baprs]-[A-Za-z0-9-]{10,}/, 'Slack token'],
  [/-----BEGIN [A-Z ]*PRIVATE KEY-----/, 'private key'],
  [/\beyJ[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{20,}\./, 'JWT'],
  [/\b(?:10|127)\.\d{1,3}\.\d{1,3}\.\d{1,3}\b/, 'private IP'],
  [/\b192\.168\.\d{1,3}\.\d{1,3}\b/, 'private IP'],
  [/\b172\.(?:1[6-9]|2\d|3[01])\.\d{1,3}\.\d{1,3}\b/, 'private IP'],
];
const authored = [...globSync('src/**/*'), ...globSync('public/api/**/*')]
  .filter((f) => statSync(f).isFile() && !/\.(png|jpe?g|webp|ico|woff2?)$/i.test(f));
const secretHits = [];
for (const f of authored) {
  const t = read(f);
  for (const [re, label] of SECRET) {
    const m = t.match(re);
    /* Documented examples are allowed, and only in prose. */
    if (m && !(label === 'private IP' && f.endsWith('.md'))) secretHits.push(`${f}: ${label} ${m[0]}`);
  }
}
report('secrets', secretHits);

/* House style. */
report('style', files.filter((f) => f.startsWith('src') && read(f).includes('—')));

/* The changelog, accessibility, security policy and governance pages are
   generated from the application repository. When that checkout is absent they
   render a link instead, which is a valid page and would otherwise pass every
   check above. */
const generated = [
  ['dist/docs/changelog/index.html', 'CHANGELOG.md'],
  ['dist/docs/accessibility/index.html', 'ACCESSIBILITY.md'],
  ['dist/docs/security-policy/index.html', 'SECURITY.md'],
  ['dist/docs/governance/index.html', 'GOVERNANCE.md'],
];
report(
  'genpage',
  generated
    .filter(([f]) => existsSync(f))
    .filter(([f]) => read(f).includes('was not available for this build'))
    .map(([f, src]) => `${f} fell back: ${src} was not read. Set STACKYARD_REPO.`),
);

/* The landing page release badge is read from the application repository's
   api/package.json at build time. Without that checkout it renders nothing, and
   a footer missing its version passes every check above. */
const landing = 'dist/index.html';
report(
  'verbadge',
  existsSync(landing) && !/class="verbadge" data-version="\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?"/.test(read(landing))
    ? [`${landing}: no release badge. api/package.json was not read. Set STACKYARD_REPO.`]
    : [],
);

/* The docs draw their interface icons from the app's icon set. A Starlight icon
   that src/lib/starlight-icon-map.ts replaces must not ship, and every mapped
   name must still exist in Starlight. */
const ICON_SRC = 'node_modules/@astrojs/starlight/components-internals/Icons.ts';
const mappedIcons = [...read('src/lib/starlight-icon-map.ts').matchAll(/^\s+'?([\w-]+)'?: \{ id:/gm)].map((m) => m[1]);
const starlightIcons = new Map(
  existsSync(ICON_SRC) ? [...read(ICON_SRC).matchAll(/^\t'?([\w-]+)'?:\s*'<path d="([^"]+)"/gm)].map((m) => [m[1], m[2]]) : [],
);
const docsHtml = html.filter((f) => f.startsWith(join(DIST, 'docs')));
report('icons', [
  ...mappedIcons.filter((name) => !starlightIcons.has(name)).map((name) => `${name}: no longer a Starlight icon`),
  ...mappedIcons.flatMap((name) => {
    const d = starlightIcons.get(name);
    if (!d) return [];
    const hits = docsHtml.filter((f) => read(f).includes(`d="${d}"`));
    return hits.length ? [`${name}: Starlight's icon still on ${hits.length} page(s), e.g. ${relative(DIST, hits[0])}`] : [];
  }),
]);

/* The placeholder domain must never ship. */
report('domain', html.filter((f) => read(f).includes('stackyard.example')).map((f) => relative(DIST, f)));

console.log(problems.length ? `\nFAIL: ${problems.length} problem(s)` : '\nPASS');
process.exit(problems.length ? 1 : 0);
